"""
Infer whether an observed human trajectory was generated by an
independent or collaborative human policy.

The assistant is assumed to always take A:wait.

Inputs:
    1. single-human VI JSON
    2. joint human+assistant VI JSON
    3. observed human trajectory JSON
    4. maze

At every human action:
    - construct the independent-human state
    - construct the collaborative joint state
    - obtain Q-values for both policies
    - convert Q-values to Boltzmann probabilities
    - evaluate the probability of the observed action
    - update cumulative log-likelihoods
    - calculate posterior P(collaborative | trajectory)

The output preserves the basic trajectory fields used by the
visualization code, while adding likelihood/inference information.
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
from typing import Dict, FrozenSet, List, Optional, Tuple

from value_iteration import load_maze, parse_goal_spec
from joint_value_iteration import (
    JointState,
    initial_joint_state,
    joint_successors,
    joint_state_key,
)


# ============================================================
# State-key helpers
# ============================================================

def single_state_key(
    pos: Tuple[int, int],
    keys: FrozenSet[str],
    unlocked: FrozenSet[str],
    gems: FrozenSet[str],
    initial_keys: Optional[FrozenSet[str]] = None,
) -> str:
    """
    Reproduce the state-key format used by the single-human VI.
    """

    d: Dict[str, object] = {
        "pos": list(pos),
        "keys": sorted(keys),
    }

    if initial_keys is not None:
        d["initial_keys"] = sorted(initial_keys)

    d["unlocked"] = sorted(unlocked)
    d["gems"] = sorted(gems)

    return json.dumps(d, separators=(",", ":"))


def human_visible_initial_keys(
    maze,
    keysA: FrozenSet[str],
    unlocked: FrozenSet[str],
) -> FrozenSet[str]:
    """
    Reproduce the interpretation used by the existing mixed-policy
    rollout.

    The independent human does not explicitly model the assistant,
    but the shared door/key availability needs to be projected into
    the single-human state representation.
    """

    doors_to_keys = {
        f"key:{door.split(':')[1]}"
        for door in unlocked
    }

    all_key_types = frozenset(maze.keys.keys())

    # Keys currently held by the assistant are no longer available
    # to the independent human unless their corresponding door is
    # already unlocked.
    return (all_key_types - keysA) | doors_to_keys


# ============================================================
# JSON helpers
# ============================================================

def load_goal_solution(data: dict, goal_key: str) -> dict:
    """
    Find a goal solution, accepting either 'red' or 'H:red'.
    """

    goals = data.get("goals", {})

    candidates = [goal_key]

    if goal_key.startswith("H:"):
        candidates.append(goal_key[2:])
    else:
        candidates.append(f"H:{goal_key}")

    for key in candidates:
        if key in goals:
            return goals[key]

    if len(goals) == 1:
        return next(iter(goals.values()))

    raise KeyError(
        f"Could not find goal {goal_key!r} in JSON. "
        f"Available goals: {list(goals)}"
    )


def get_q_values(table: dict, state_key: str) -> Dict[str, float]:
    """
    Retrieve finite Q-values for a state.
    """

    q = table.get(state_key)

    if q is None:
        raise KeyError(
            f"State is missing from Q table: {state_key}"
        )

    return {
        action: float(value)
        for action, value in q.items()
        if value is not None
    }


# ============================================================
# Numerically stable Boltzmann policy
# ============================================================

def boltzmann_probabilities(
    q_values: Dict[str, float],
    beta: float,
) -> Dict[str, float]:
    """
    Convert Q-values into Boltzmann probabilities.

        P(a|s) = exp(beta * Q(s,a))
                 -------------------
                 sum_a' exp(beta * Q(s,a'))

    Your Q-values are negative cost-to-go values, so larger Q
    means lower cost and therefore a more preferred action.
    """

    if not q_values:
        raise ValueError("Cannot calculate softmax of empty Q table.")

    if beta < 0:
        raise ValueError("beta must be non-negative.")

    if beta == 0:
        p = 1.0 / len(q_values)
        return {action: p for action in q_values}

    # Numerically stable softmax.
    max_beta_q = max(beta * q for q in q_values.values())

    exp_values = {
        action: math.exp(beta * q - max_beta_q)
        for action, q in q_values.items()
    }

    denominator = sum(exp_values.values())

    return {
        action: value / denominator
        for action, value in exp_values.items()
    }


# ============================================================
# Joint-state helpers
# ============================================================

def human_successors(
    maze,
    state: JointState,
) -> Dict[str, JointState]:
    """
    Return executable human actions from the current joint state.

    The assistant is assumed to be waiting, so collision checking is
    done against the assistant's current position.
    """

    posH, keysH, gemsH, posA, keysA, unlocked, turn = state

    if turn != "human":
        raise RuntimeError(
            f"Expected human turn, got {turn!r}"
        )

    successors = {}

    for action, next_state, _, _ in joint_successors(maze, state):

        if not action.startswith("H:"):
            continue

        # The maze does not allow the human to occupy the assistant's
        # current cell.
        next_posH = next_state[0]

        if next_posH == posA:
            continue

        successors[action] = next_state

    return successors


def assistant_wait_successor(
    maze,
    state: JointState,
) -> Tuple[str, JointState, float, float]:
    """
    Apply A:wait.

    The assistant is assumed to always wait.
    """

    for action, next_state, human_cost, assistant_cost in joint_successors(
        maze, state
    ):
        if action == "A:wait":
            return action, next_state, human_cost, assistant_cost

    raise RuntimeError(
        "A:wait is not executable from state "
        f"{joint_state_key(state)}"
    )


# ============================================================
# State projection
# ============================================================

def projected_human_key(
    maze,
    state: JointState,
) -> str:
    """
    Project a joint environment state into the state representation
    expected by the independent-human Q table.
    """

    (
        posH,
        keysH,
        gemsH,
        _posA,
        keysA,
        unlocked,
        _turn,
    ) = state

    initial_keys = human_visible_initial_keys(
        maze,
        keysA,
        unlocked,
    )

    return single_state_key(
        posH,
        keysH,
        unlocked,
        gemsH,
        initial_keys,
    )


# ============================================================
# Action probability
# ============================================================

def get_independent_action_probabilities(
    maze,
    state: JointState,
    single_q: dict,
    beta: float,
) -> Tuple[Dict[str, float], str]:
    """
    Get Boltzmann probabilities for the independent-human policy.

    The single-human Q table contains actions such as:
        up
        down
        left
        right
        wait

    Only actions that are actually executable in the real joint
    environment are included in the probability normalization.
    """

    state_key = projected_human_key(maze, state)

    q_values = get_q_values(
        single_q,
        state_key,
    )

    executable = human_successors(
        maze,
        state,
    )

    executable_raw_actions = {}

    for action in executable:
        raw_action = action.split(":", 1)[1]

        if raw_action in q_values:
            executable_raw_actions[raw_action] = q_values[raw_action]

    if not executable_raw_actions:
        raise RuntimeError(
            "No executable independent-human actions with Q-values "
            f"for state {state_key}"
        )

    probabilities = boltzmann_probabilities(
        executable_raw_actions,
        beta,
    )

    return probabilities, state_key


def get_collaborative_action_probabilities(
    maze,
    state: JointState,
    joint_q: dict,
    beta: float,
) -> Tuple[Dict[str, float], str]:
    """
    Get Boltzmann probabilities for the collaborative human policy.

    The collaborative Q table uses actions such as:
        H:up
        H:down
        H:right
        H:wait
    """

    state_key = joint_state_key(state)

    q_values = get_q_values(
        joint_q,
        state_key,
    )

    executable = human_successors(
        maze,
        state,
    )

    executable_q = {}

    for action in executable:

        if action in q_values:
            executable_q[action] = q_values[action]

    if not executable_q:
        raise RuntimeError(
            "No executable collaborative-human actions with Q-values "
            f"for state {state_key}"
        )

    probabilities = boltzmann_probabilities(
        executable_q,
        beta,
    )

    return probabilities, state_key


# ============================================================
# Numerical helpers
# ============================================================

def safe_log_probability(p: float) -> float:
    """
    Return log(p), protecting against log(0).

    A true zero-probability observed action receives a large negative
    log likelihood rather than crashing the inference.
    """

    if p <= 0.0:
        return -math.inf

    return math.log(p)


def posterior_from_log_likelihoods(
    log_likelihood_independent: float,
    log_likelihood_collaborative: float,
    prior_independent: float,
    prior_collaborative: float,
) -> float:
    """
    Calculate P(C | trajectory) using log likelihoods and priors.
    """

    log_prior_I = math.log(prior_independent)
    log_prior_C = math.log(prior_collaborative)

    log_I = log_prior_I + log_likelihood_independent
    log_C = log_prior_C + log_likelihood_collaborative

    # Handle impossible hypotheses.
    if math.isinf(log_I) and log_I < 0:
        return 1.0

    if math.isinf(log_C) and log_C < 0:
        return 0.0

    # We want P(C | trajectory):
    #
    # P(C | trajectory)
    # = exp(log_C) / (exp(log_I) + exp(log_C))
    #
    # Let difference = log_I - log_C.
    # Then:
    #
    # P(C | trajectory) = 1 / (1 + exp(difference))

    difference = log_I - log_C

    if difference >= 0:
        # exp(-difference) is numerically safe here
        exp_neg_difference = math.exp(-difference)
        return exp_neg_difference / (1.0 + exp_neg_difference)
    else:
        # exp(difference) is numerically safe here
        exp_difference = math.exp(difference)
        return 1.0 / (1.0 + exp_difference)

# ============================================================
# Output formatting
# ============================================================

def make_trajectory_entry(
    t: int,
    state: JointState,
    action: Optional[str],
    pddl_action: Optional[str],
    likelihood: dict,
) -> dict:
    """
    Preserve the fields useful for the existing visualization while
    removing utility/Q-value fields.
    """

    (
        posH,
        keysH,
        gemsH,
        posA,
        keysA,
        unlocked,
        turn,
    ) = state

    entry = {
        "t": t,

        # Human position
        "x": posH[0],
        "y": posH[1],

        # Assistant position
        "rx": posA[0],
        "ry": posA[1],

        # Current actor
        "turn": turn,

        # Actual observed action
        "action": action,
        "pddl_action": pddl_action,

        # Likelihood/inference information
        **likelihood,
    }

    return entry


# ============================================================
# Main inference
# ============================================================

def infer_human_trajectory(
    maze,
    single_solution: dict,
    joint_solution: dict,
    observed_actions: List[str],
    beta: float = 1.0,
    prior_independent: float = 0.5,
    prior_collaborative: float = 0.5,
) -> dict:
    """
    Infer human type from an observed sequence of human actions.

    The assistant always waits.

    observed_actions should contain raw human actions, for example:

        [
            "H:right",
            "H:right",
            "H:up",
            "H:wait"
        ]

    or:

        [
            "right",
            "right",
            "up",
            "wait"
        ]
    """

    if prior_independent <= 0 or prior_collaborative <= 0:
        raise ValueError("Priors must be positive.")

    prior_sum = prior_independent + prior_collaborative

    prior_independent /= prior_sum
    prior_collaborative /= prior_sum

    single_q = single_solution["q_values"]
    joint_q = joint_solution["q_values"]

    state = initial_joint_state(maze)

    trajectory = []

    log_likelihood_I = 0.0
    log_likelihood_C = 0.0

    # --------------------------------------------------------
    # t = 0
    # --------------------------------------------------------

    initial_entry = make_trajectory_entry(
        t=0,
        state=state,
        action=None,
        pddl_action=None,
        likelihood={
            "likelihood": {
                "independent": 1.0,
                "collaborative": 1.0,
            },
            "p_independent": None,
            "p_collaborative": None,
            "log_lr": 0.0,
            "posterior_collaborative": prior_collaborative,
        },
    )

    trajectory.append(initial_entry)

    # --------------------------------------------------------
    # Process observed human actions
    # --------------------------------------------------------

    for t, observed_action in enumerate(
        observed_actions,
        start=1,
    ):

        # ----------------------------------------------------
        # Make sure we are at a human turn
        # ----------------------------------------------------

        if state[-1] != "human":
            raise RuntimeError(
                f"Expected human turn before observed action at t={t}, "
                f"but state has turn={state[-1]!r}."
            )

        # Normalize action representation.
        if observed_action.startswith("H:"):
            action = observed_action
        else:
            action = f"H:{observed_action}"

        # ----------------------------------------------------
        # Calculate independent probabilities
        # ----------------------------------------------------

        independent_probs, independent_state_key = (
            get_independent_action_probabilities(
                maze,
                state,
                single_q,
                beta,
            )
        )

        raw_action = action.split(":", 1)[1]

        p_independent = independent_probs.get(
            raw_action,
            0.0,
        )

        # ----------------------------------------------------
        # Calculate collaborative probabilities
        # ----------------------------------------------------

        collaborative_probs, collaborative_state_key = (
            get_collaborative_action_probabilities(
                maze,
                state,
                joint_q,
                beta,
            )
        )

        p_collaborative = collaborative_probs.get(
            action,
            0.0,
        )

        # ----------------------------------------------------
        # Update likelihoods
        # ----------------------------------------------------

        log_p_I = safe_log_probability(
            p_independent
        )

        log_p_C = safe_log_probability(
            p_collaborative
        )

        if math.isinf(log_likelihood_I) and log_likelihood_I < 0:
            pass
        elif math.isinf(log_p_I) and log_p_I < 0:
            log_likelihood_I = -math.inf
        else:
            log_likelihood_I += log_p_I

        if math.isinf(log_likelihood_C) and log_likelihood_C < 0:
            pass
        elif math.isinf(log_p_C) and log_p_C < 0:
            log_likelihood_C = -math.inf
        else:
            log_likelihood_C += log_p_C

        # ----------------------------------------------------
        # Log likelihood ratio
        #
        # Positive -> evidence for collaborative
        # Negative -> evidence for independent
        # ----------------------------------------------------

        if (
            math.isinf(log_likelihood_C)
            and log_likelihood_C < 0
        ):
            log_lr = -math.inf

        elif (
            math.isinf(log_likelihood_I)
            and log_likelihood_I < 0
        ):
            log_lr = math.inf

        else:
            log_lr = (
                log_likelihood_C
                - log_likelihood_I
            )

        # ----------------------------------------------------
        # Posterior P(C | trajectory_0:t)
        # ----------------------------------------------------

        posterior_collaborative = (
            posterior_from_log_likelihoods(
                log_likelihood_I,
                log_likelihood_C,
                prior_independent,
                prior_collaborative,
            )
        )

        # ----------------------------------------------------
        # Execute the OBSERVED human action in the real
        # environment.
        #
        # This is important: we do NOT choose an action based
        # on either Q table. We are evaluating an observed
        # trajectory.
        # ----------------------------------------------------

        successors = human_successors(
            maze,
            state,
        )

        if action not in successors:
            raise RuntimeError(
                f"Observed action {action!r} is not executable "
                f"at t={t} from state "
                f"{joint_state_key(state)}"
            )

        next_state = successors[action]

        # ----------------------------------------------------
        # Convert to PDDL
        # ----------------------------------------------------

        from joint_value_iteration import to_pddl_action

        raw_action = action.split(":", 1)[1]

        pddl_action = to_pddl_action(
            maze,
            "human",
            raw_action,
        )

        # ----------------------------------------------------
        # Store trajectory entry
        # ----------------------------------------------------

        likelihood_info = {
            # Cumulative likelihood under each model.
            #
            # These are normal-space likelihoods. For long
            # trajectories they may become extremely small.
            "likelihood": {
                "independent": (
                    0.0
                    if math.isinf(log_likelihood_I)
                    else math.exp(log_likelihood_I)
                ),
                "collaborative": (
                    0.0
                    if math.isinf(log_likelihood_C)
                    else math.exp(log_likelihood_C)
                ),
            },

            # Probability of THIS observed action.
            "p_independent": p_independent,
            "p_collaborative": p_collaborative,

            # Cumulative log likelihood ratio.
            "log_lr": log_lr,

            # Cumulative posterior.
            "posterior_collaborative": posterior_collaborative,
        }

        entry = make_trajectory_entry(
            t=t,
            state=next_state,
            action=action,
            pddl_action=pddl_action,
            likelihood=likelihood_info,
        )

        trajectory.append(entry)

        # ----------------------------------------------------
        # After the observed human action, the assistant waits.
        #
        # We need to execute A:wait so that the next observed
        # human action starts from a human-turn state.
        # ----------------------------------------------------

        state = next_state

        if t < len(observed_actions):

            if state[-1] != "assistant":
                raise RuntimeError(
                    f"Expected assistant turn after human action "
                    f"at t={t}, but got {state[-1]!r}."
                )

            (
                _wait_action,
                state,
                _human_cost,
                _assistant_cost,
            ) = assistant_wait_successor(
                maze,
                state,
            )

    # --------------------------------------------------------
    # Final result
    # --------------------------------------------------------

    final_posterior = (
        trajectory[-1]["posterior_collaborative"]
        if trajectory
        else prior_collaborative
    )

    result = {
        "solver": "human_type_inference",
        "assistant_policy": "always_wait",

        "beta": beta,

        "prior": {
            "independent": prior_independent,
            "collaborative": prior_collaborative,
        },

        "posterior_collaborative": final_posterior,

        "posterior_independent": (
            1.0 - final_posterior
        ),

        "log_likelihood": {
            "independent": log_likelihood_I,
            "collaborative": log_likelihood_C,
        },

        "n_human_actions": len(observed_actions),

        "trajectory": trajectory,

        "pddl_names": maze.pddl_names,
    }

    return result


# ============================================================
# Load observed trajectory
# ============================================================

def load_observed_actions(
    trajectory_data: dict,
) -> List[str]:
    """
    Accept several convenient input formats.

    Preferred:

        {
            "trajectory": [
                {"t": 0, "action": null},
                {"t": 1, "action": "H:right"},
                ...
            ]
        }

    Also accepts:

        {
            "path": ["H:right", "H:up", ...]
        }

    or simply a list:

        ["H:right", "H:up", ...]
    """

    if isinstance(trajectory_data, list):
        actions = trajectory_data

    elif "path" in trajectory_data:
        actions = trajectory_data["path"]

    elif "trajectory" in trajectory_data:
        actions = [
            entry["action"]
            for entry in trajectory_data["trajectory"]
            if entry.get("action") is not None
        ]

    else:
        raise KeyError(
            "Could not find observed actions. Expected "
            "'trajectory', 'path', or a list."
        )

    result = []

    for action in actions:

        if action is None:
            continue

        # If the trajectory contains assistant actions, ignore them.
        if isinstance(action, str) and action.startswith("A:"):
            continue

        result.append(action)

    return result


# ============================================================
# CLI
# ============================================================

def main() -> None:

    parser = argparse.ArgumentParser(
        description=(
            "Infer whether an observed human trajectory is "
            "independent or collaborative."
        )
    )

    parser.add_argument(
        "--single",
        type=Path,
        default=(
            Path(__file__).resolve().parent
            / "mazes"
            / "value_iteration_results.json"
        ),
        help="Single-human VI result JSON.",
    )

    parser.add_argument(
        "--joint",
        type=Path,
        default=(
            Path(__file__).resolve().parent
            / "mazes"
            / "joint_value_iteration_results.json"
        ),
        help="Joint human+assistant VI result JSON.",
    )

    parser.add_argument(
        "--trajectory",
        type=Path,
        required=True,
        help="Observed human trajectory JSON.",
    )

    parser.add_argument(
        "--maze",
        type=Path,
        default=(
            Path(__file__).resolve().parent
            / "mazes"
            / "sample.txt"
        ),
    )

    parser.add_argument(
        "--out",
        type=Path,
        default=(
            Path(__file__).resolve().parent
            / "mazes"
            / "human_type_inference_results.json"
        ),
    )

    parser.add_argument(
        "--human-goal",
        default="both",
    )

    parser.add_argument(
        "--beta",
        type=float,
        default=10.0,
        help="Boltzmann rationality / inverse-temperature parameter.",
    )

    parser.add_argument(
        "--prior-independent",
        type=float,
        default=0.5,
    )

    parser.add_argument(
        "--prior-collaborative",
        type=float,
        default=0.5,
    )

    args = parser.parse_args()

    # --------------------------------------------------------
    # Load files
    # --------------------------------------------------------

    with args.single.open(
        "r",
        encoding="utf-8",
    ) as f:
        single_data = json.load(f)

    with args.joint.open(
        "r",
        encoding="utf-8",
    ) as f:
        joint_data = json.load(f)

    with args.trajectory.open(
        "r",
        encoding="utf-8",
    ) as f:
        observed_data = json.load(f)

    maze = load_maze(args.maze)

    # --------------------------------------------------------
    # Extract the requested goal solution
    # --------------------------------------------------------

    single_solution = load_goal_solution(
        single_data,
        args.human_goal,
    )

    joint_solution = load_goal_solution(
        joint_data,
        args.human_goal,
    )

    # --------------------------------------------------------
    # Extract observed human actions
    # --------------------------------------------------------

    observed_actions = load_observed_actions(
        observed_data
    )

    print(
        f"Loaded {len(observed_actions)} observed human actions."
    )

    print(
        f"Boltzmann beta = {args.beta}"
    )

    # --------------------------------------------------------
    # Run inference
    # --------------------------------------------------------

    result = infer_human_trajectory(
        maze=maze,
        single_solution=single_solution,
        joint_solution=joint_solution,
        observed_actions=observed_actions,
        beta=args.beta,
        prior_independent=args.prior_independent,
        prior_collaborative=args.prior_collaborative,
    )

    # --------------------------------------------------------
    # Add source information
    # --------------------------------------------------------

    result["source_files"] = {
        "single_human": str(args.single),
        "joint": str(args.joint),
        "observed_trajectory": str(args.trajectory),
        "maze": str(args.maze),
    }

    # --------------------------------------------------------
    # Write output
    # --------------------------------------------------------

    args.out.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    with args.out.open(
        "w",
        encoding="utf-8",
    ) as f:
        json.dump(
            result,
            f,
            indent=2,
        )

    print(
        f"Final P(collaborative) = "
        f"{result['posterior_collaborative']:.4f}"
    )

    print(
        f"Final P(independent) = "
        f"{result['posterior_independent']:.4f}"
    )

    print(
        f"Wrote inference result to {args.out}"
    )


if __name__ == "__main__":
    main()